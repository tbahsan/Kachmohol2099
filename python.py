def run(command: list[str]) -> None:
    print("+", " ".join(command))
    subprocess.run(command, check=True)


def extract_project(destination: Path) -> None:
    archive = base64.b85decode("".join(PAYLOAD.split()))
    with zipfile.ZipFile(io.BytesIO(archive)) as bundle:
        bundled = set(bundle.namelist())
        expected = set(PROJECT_FILES)
        if bundled != expected:
            raise RuntimeError("Embedded project manifest does not match the archive")
        for name in PROJECT_FILES:
            path = PurePosixPath(name)
            if path.is_absolute() or ".." in path.parts:
                raise RuntimeError(f"Unsafe embedded path: {name}")
            target = destination.joinpath(*path.parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(bundle.read(name))
            print(f"created  {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Kachmohol 2099 Version 1 in the current repository")
    parser.add_argument("--build", action="store_true", help="also run npm install and npm run build")
    parser.add_argument("--clean", action="store_true", help="remove generated project files before writing them")
    args = parser.parse_args()
    destination = Path.cwd()

    if args.clean:
        for name in PROJECT_FILES:
            target = destination / name
            if target.is_file():
                target.unlink()
        for folder in (destination / "src", destination / "docs", destination / "public"):
            if folder.exists():
                shutil.rmtree(folder)

    extract_project(destination)
    print("\nKachmohol 2099 Version 1 source has been generated.")

    if args.build:
        if not shutil.which("npm"):
            print("npm was not found. Use the default Node.js Codespace image.", file=sys.stderr)
            return 2
        run(["npm", "install"])
        run(["npm", "run", "build"])
        print("\nBuild successful.")
    else:
        print("Next: npm install && npm run build")

    print("Then commit and push to main; the included GitHub Actions workflow deploys Pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
